# ── Helpers ────────────────────────────────────────────────────────────────────

def _load_wav_as_pcm(path: Path) -> bytes:
    import wave, struct
    with wave.open(str(path), "rb") as wf:
        frames = wf.readframes(wf.getnframes())
        # If stereo, mix to mono
        if wf.getnchannels() == 2:
            samples = struct.unpack(f"<{len(frames)//2}h", frames)
            mono = [int((samples[i] + samples[i+1]) / 2) for i in range(0, len(samples), 2)]
            frames = struct.pack(f"<{len(mono)}h", *mono)
    return frames


# ── STT spike ─────────────────────────────────────────────────────────────────

async def spike_stt(wav_path: Path) -> dict:
    print("\n=== STT Spike ===")
    if not wav_path.exists():
        print(f"⚠  No sample WAV found at {wav_path}. Skipping STT spike.")
        print("   Please provide a 5-10 s Tamil WAV at tests/sample_ta.wav")
        return {
            "partials": "SKIPPED – no sample WAV",
            "final_text": "SKIPPED",
            "latency": "N/A",
            "notes": "Provide tests/sample_ta.wav and re-run.",
        }

    try:
        import io, wave
        from gnani.stt import GnaniSTTStreamClient

        with wave.open(str(wav_path), "rb") as wf:
            raw_pcm = wf.readframes(wf.getnframes())

        # Append silence to allow VAD to finalize the segment
        silence = b"\x00\x00" * 24000  # 1.5 s of silence at 16 kHz
        full_audio = raw_pcm + silence

        transcripts = []
        latencies = []
        t0 = time.monotonic()

        async with GnaniSTTStreamClient(
            api_key=GNANI_API_KEY,
            language_code=STT_LANGUAGE,
            sample_rate=16000,
        ) as client:
            buf = io.BytesIO(full_audio)
            await client.stream_audio(
                buf,
                on_transcript=lambda e: (transcripts.append(e.text), latencies.append(getattr(e, "latency", None))),
            )

        final_text = " ".join(transcripts)
        first_latency = latencies[0] if latencies else None
        print(f"  FINAL: {final_text!r} (latency={first_latency} ms)")

        return {
            "partials": str(len(transcripts)),
            "final_text": final_text,
            "latency": str(first_latency) if first_latency else "N/A",
            "notes": "OK (via gnani-vachana GnaniSTTStreamClient)",
        }

    except Exception as exc:
        print(f"  STT error: {exc}")
        return {
            "partials": f"ERROR: {exc}",
            "final_text": "ERROR",
            "latency": "N/A",
            "notes": str(exc),
        }


# ── TTS spike ──────────────────────────────────────────────────────────────────

async def spike_tts() -> dict:
    print("\n=== TTS Spike ===")

    test_sentences = [
        ("baseline", "வணக்கம். நான் உங்களுக்கு help பண்ண ready."),
        ("tag_mid", "வணக்கம். <excited> இது ரொம்ப சூப்பர்!"),
        ("tag_start_sent2", "வணக்கம். <pauses> ஒரு நிமிஷம் சொல்றேன்."),
    ]

    results = {}
    tts_format = "unknown"
    tts_rate = "unknown"
    total_latency = []

    try:
        import httpx
        async with httpx.AsyncClient() as client:
            for name, text in test_sentences:
                payload = {
                    "text": text,
                    "model": TTS_MODEL,
                    "voice": TTS_VOICE,
                    "language": "ta-IN",
                    "audio_config": {
                        "sample_rate": TTS_SAMPLE_RATE,
                        "encoding": "linear_pcm",
                        "container": "wav",
                    },
                }
                headers = {"X-API-Key-ID": GNANI_API_KEY, "Content-Type": "application/json"}
                t0 = time.monotonic()
                resp = await client.post(TTS_REST_URL, json=payload, headers=headers, timeout=15.0)
                latency = (time.monotonic() - t0) * 1000
                total_latency.append(latency)

                if resp.status_code == 200:
                    audio = resp.content
                    # Try to detect format from WAV header
                    if audio[:4] == b"RIFF":
                        import struct
                        tts_format = "wav"
                        tts_rate = struct.unpack_from("<I", audio, 24)[0]
                    print(f"  [{name}] OK – {len(audio)} bytes, {latency:.0f} ms")
                    # Save for manual listening
                    out_path = Path(f"docs/tts_spike_{name}.wav")
                    out_path.parent.mkdir(exist_ok=True)
                    out_path.write_bytes(audio)
                    results[name] = "OK"
                else:
                    print(f"  [{name}] ERROR {resp.status_code}: {resp.text[:200]}")
                    results[name] = f"ERROR {resp.status_code}"

    except Exception as exc:
        print(f"  TTS error: {exc}")
        return {
            "format": "ERROR",
            "rate": "ERROR",
            "latency": "N/A",
            "tag_finding": f"ERROR: {exc}",
            "strategy": "unknown",
            "notes": str(exc),
        }

    avg_latency = sum(total_latency) / len(total_latency) if total_latency else 0
    return {
        "format": tts_format,
        "rate": str(tts_rate),
        "latency": f"{avg_latency:.0f}",
        "tag_finding": "TODO: Listen to docs/tts_spike_*.wav files and document whether the tag effect persists beyond the tagged sentence.",
        "strategy": "TODO: Update tags.py and tts.py based on tag-persistence finding.",
        "notes": f"Results: {results}",
    }


# ── Evon LLM spike ────────────────────────────────────────────────────────────

async def spike_evon() -> dict:
    print("\n=== LLM Spike (Evon with Groq fallback) ===")

    test_messages = [
        {"role": "system", "content": "You are a Tamil government services assistant. Reply in short spoken Tamil. Do NOT include <think> blocks."},
        {"role": "user", "content": "பாஸ்போர்ட் apply பண்றது எப்படி? சுருக்கமா சொல்லுங்க."},
    ]

    from app import llm

    t0 = time.monotonic()
    first_token_time = None
    tokens: list[str] = []

    try:
        async for delta in llm.stream(test_messages):
            if first_token_time is None:
                first_token_time = time.monotonic()
                ttft = (first_token_time - t0) * 1000
                print(f"  TTFT: {ttft:.0f} ms")
            tokens.append(delta)
            print(delta, end="", flush=True)

        total_time = time.monotonic() - t0
        tps = len(tokens) / total_time if total_time > 0 else 0
        print(f"\n  Total tokens: {len(tokens)}, {tps:.1f} tok/s")

        return {
            "option": "Evon (Primary) / Groq (Fallback: " + (GROQ_MODEL if GROQ_API_KEY else "disabled") + ")",
            "url": GROQ_BASE_URL if GROQ_API_KEY else EVON_BASE_URL,
            "model": GROQ_MODEL if GROQ_API_KEY else EVON_MODEL,
            "ttft": f"{(first_token_time - t0) * 1000:.0f}" if first_token_time else "N/A",
            "tps": f"{tps:.1f}",
            "thinking": "System prompt instruction 'Do NOT include <think> blocks'",
            "notes": "OK",
        }

    except Exception as exc:
        print(f"\n  LLM error: {exc}")
        return {
            "option": "UNKNOWN – all providers failed",
            "url": EVON_BASE_URL,
            "model": EVON_MODEL,
            "ttft": "N/A",
            "tps": "N/A",
            "thinking": "N/A",
            "notes": f"ERROR: {exc}",
        }


